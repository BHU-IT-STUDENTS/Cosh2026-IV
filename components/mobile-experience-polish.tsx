"use client";

import { useEffect } from "react";

/** Shared mobile safety layer for the admin and protocol application shells. */
export function MobileExperiencePolish() {
  useEffect(() => {
    const humanizeCopy = () => {
      const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
      const replacements: Array<[RegExp, string]> = [
        [/\bAI[- ]generated\b/gi, "prepared"],
        [/\bgenerated by AI\b/gi, "prepared for this celebration"],
        [/\bAI assistant\b/gi, "event support"],
      ];
      let node: Text | null;
      while ((node = walker.nextNode() as Text | null)) {
        if (node.parentElement?.closest("script, style")) continue;
        const original = node.nodeValue || "";
        const revised = replacements.reduce((value, [pattern, replacement]) => value.replace(pattern, replacement), original);
        if (revised !== original) node.nodeValue = revised;
      }
    };
    const markSafeAreas = () => {
      if (!document.querySelector(".protocol-app-nav, .admin-app-nav")) return;
      document.querySelectorAll("main").forEach((main) => main.classList.add("mobile-nav-safe"));
      const nav = document.querySelector<HTMLElement>(".protocol-app-nav, .admin-app-nav");
      if (!nav || window.innerWidth > 800) return;
      const navTop = nav.getBoundingClientRect().top;
      document.querySelectorAll<HTMLElement>("main a, main button").forEach((action) => {
        if (action.closest(".protocol-app-nav, .admin-app-nav")) return;
        const rect = action.getBoundingClientRect();
        if (rect.top < navTop && rect.bottom > navTop - 12) action.classList.add("mobile-action-clearance");
      });
    };
    humanizeCopy();
    markSafeAreas();
    const observer = new MutationObserver(() => { humanizeCopy(); markSafeAreas(); });
    observer.observe(document.body, { childList: true, subtree: true });
    window.addEventListener("resize", markSafeAreas);
    window.addEventListener("scroll", markSafeAreas, true);
    return () => { observer.disconnect(); window.removeEventListener("resize", markSafeAreas); window.removeEventListener("scroll", markSafeAreas, true); };
  }, []);

  return <style>{`
    @media (max-width: 800px) {
      main.mobile-nav-safe { padding-bottom: calc(7.5rem + env(safe-area-inset-bottom)) !important; scroll-padding-bottom: calc(7.5rem + env(safe-area-inset-bottom)); }
      .protocol-app-nav, .admin-app-nav { min-height: 4.9rem !important; height: auto !important; padding: .45rem .65rem calc(.45rem + env(safe-area-inset-bottom)) !important; gap: .2rem !important; background: rgba(255,253,248,.98) !important; border-top: 1px solid #e5dccb !important; box-shadow: 0 -8px 22px rgba(18,60,50,.10) !important; }
      .protocol-app-nav a, .protocol-app-nav button, .admin-app-nav a, .admin-app-nav button { min-width: 0 !important; flex: 1 1 0 !important; min-height: 3.8rem !important; padding: .3rem .15rem !important; border-radius: .65rem !important; font-size: .72rem !important; line-height: 1.1 !important; white-space: nowrap !important; }
      .protocol-app-nav svg, .admin-app-nav svg { width: 1.35rem !important; height: 1.35rem !important; }
      .protocol-detail-layer, .modal-layer { z-index: 1400 !important; padding-bottom: 1rem !important; }
      body:has(.protocol-detail-layer) .protocol-app-nav, body:has(.modal-layer) .protocol-app-nav, body:has(.protocol-detail-layer) .admin-app-nav, body:has(.modal-layer) .admin-app-nav { display: none !important; }
      .mobile-action-clearance { position: relative !important; z-index: 2 !important; transform: translateY(-1.35rem) !important; }
    }
  `}</style>;
}
